import Config

# The adapter has to be chosen at compile time. Production defaults to
# Postgres (Gigalixir); the Dockerfile sets QA_ECTO_ADAPTER=sqlite because the
# VM/Cloudflare stack keeps using SQLite.
#
# The name is prefixed to avoid colliding with ECTO_ADAPTER, which ecto_sql
# reads for its own test suite while dependencies compile.
ecto_adapter =
  if System.get_env("QA_ECTO_ADAPTER") == "sqlite" do
    Ecto.Adapters.SQLite3
  else
    Ecto.Adapters.Postgres
  end

config :qa_app, ecto_adapter: ecto_adapter

# Note we also include the path to a cache manifest
# containing the digested version of static files. This
# manifest is generated by the `mix assets.deploy` task,
# which you should run after static files are built and
# before starting your production server.
config :qa_app, QaAppWeb.Endpoint, cache_static_manifest: "priv/static/cache_manifest.json"

# Force using SSL in production. This also sets the "strict-security-transport" header,
# known as HSTS. If you have a health check endpoint, you may want to exclude it below.
# Note `:force_ssl` is required to be set at compile-time.
config :qa_app, QaAppWeb.Endpoint,
  force_ssl: [
    rewrite_on: [:x_forwarded_proto],
    exclude: [
      # The container health check talks plain HTTP to localhost.
      paths: ["/healthz"],
      hosts: ["localhost", "127.0.0.1"]
    ]
  ]

# Configure Swoosh API Client
config :swoosh, api_client: Swoosh.ApiClient.Req

# Disable Swoosh Local Memory Storage
config :swoosh, local: false

# Do not print debug messages in production
config :logger, level: :info

# Runtime production configuration, including reading
# of environment variables, is done on config/runtime.exs.
